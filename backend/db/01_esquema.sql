-- Alertas Zaror: esquema inicial para Oracle Autonomous.
-- Ejecutar UNA vez como script (F5) en Database Actions > SQL, con ALERTAS_APP o con ADMIN.
-- Para empezar de cero, ejecutar antes 99_borrar_esquema.sql.

-- Se ejecuta en el esquema de la aplicacion aunque estes conectado como ADMIN.
ALTER SESSION SET CURRENT_SCHEMA = ALERTAS_APP;

CREATE TABLE CUADRAS (
    ID      NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    CALLE   VARCHAR2(80) NOT NULL,
    TRAMO   VARCHAR2(30) NOT NULL,
    SECTOR  VARCHAR2(40) NOT NULL,
    CONSTRAINT UQ_CUADRAS UNIQUE (CALLE, TRAMO)
);

CREATE TABLE USUARIOS (
    ID                 NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    NOMBRE             VARCHAR2(100) NOT NULL,
    TELEFONO           VARCHAR2(9)   NOT NULL,
    DIRECCION          VARCHAR2(150) NOT NULL,
    CUADRA_ID          NUMBER,
    CLAVE_HASH         VARCHAR2(120) NOT NULL,
    ROL                VARCHAR2(20)  DEFAULT 'VECINO' NOT NULL,
    ESTADO             VARCHAR2(20)  DEFAULT 'PENDIENTE' NOT NULL,
    INTENTOS_FALLIDOS  NUMBER(2)     DEFAULT 0 NOT NULL,
    BLOQUEADO_HASTA    TIMESTAMP,
    FECHA_REGISTRO     TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_APROBACION   TIMESTAMP,
    APROBADO_POR       NUMBER,
    CONSTRAINT UQ_USUARIOS_TELEFONO UNIQUE (TELEFONO),
    CONSTRAINT CK_USUARIOS_ROL CHECK (ROL IN ('VECINO', 'ADMINISTRADOR')),
    CONSTRAINT CK_USUARIOS_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'APROBADO', 'RECHAZADO')),
    -- Un vecino aprobado debe tener su cuadra asignada; el administrador puede no tenerla.
    CONSTRAINT CK_USUARIOS_CUADRA CHECK (ESTADO <> 'APROBADO' OR CUADRA_ID IS NOT NULL OR ROL = 'ADMINISTRADOR'),
    CONSTRAINT FK_USUARIOS_CUADRA FOREIGN KEY (CUADRA_ID) REFERENCES CUADRAS (ID),
    CONSTRAINT FK_USUARIOS_APROBADO_POR FOREIGN KEY (APROBADO_POR) REFERENCES USUARIOS (ID)
);

CREATE TABLE ALERTAS (
    ID              NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USUARIO_ID      NUMBER        NOT NULL,
    TIPO            VARCHAR2(30)  NOT NULL,
    DESCRIPCION     VARCHAR2(500) NOT NULL,
    UBICACION       VARCHAR2(200) NOT NULL,
    FOTO_URI        VARCHAR2(500),
    ESTADO          VARCHAR2(20)  DEFAULT 'ACTIVA' NOT NULL,
    FECHA_HORA      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    ATENDIDA_POR    NUMBER,
    FECHA_ATENCION  TIMESTAMP,
    CONSTRAINT CK_ALERTAS_TIPO CHECK (TIPO IN ('EMERGENCIA', 'FALLA_ALARMA', 'SOLICITUD_APOYO')),
    CONSTRAINT CK_ALERTAS_ESTADO CHECK (ESTADO IN ('ACTIVA', 'ATENDIDA', 'CANCELADA')),
    CONSTRAINT FK_ALERTAS_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID),
    CONSTRAINT FK_ALERTAS_ATENDIDA_POR FOREIGN KEY (ATENDIDA_POR) REFERENCES USUARIOS (ID)
);

-- Relacion entre dos vecinos registrados. El contacto debe aceptar (PENDIENTE -> ACTIVO).
CREATE TABLE CONTACTOS_CONFIANZA (
    ID                   NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    USUARIO_ID           NUMBER NOT NULL,
    CONTACTO_USUARIO_ID  NUMBER NOT NULL,
    ESTADO               VARCHAR2(20) DEFAULT 'PENDIENTE' NOT NULL,
    FECHA_REGISTRO       TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT UQ_CONTACTOS UNIQUE (USUARIO_ID, CONTACTO_USUARIO_ID),
    CONSTRAINT CK_CONTACTOS_ESTADO CHECK (ESTADO IN ('PENDIENTE', 'ACTIVO', 'RECHAZADO', 'DESACTIVADO')),
    CONSTRAINT CK_CONTACTOS_DISTINTOS CHECK (USUARIO_ID <> CONTACTO_USUARIO_ID),
    CONSTRAINT FK_CONTACTOS_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID),
    CONSTRAINT FK_CONTACTOS_CONTACTO FOREIGN KEY (CONTACTO_USUARIO_ID) REFERENCES USUARIOS (ID)
);

-- Oracle no indexa las claves foraneas solas.
CREATE INDEX IX_USUARIOS_CUADRA ON USUARIOS (CUADRA_ID);
CREATE INDEX IX_ALERTAS_USUARIO ON ALERTAS (USUARIO_ID);
CREATE INDEX IX_ALERTAS_FECHA ON ALERTAS (FECHA_HORA);
CREATE INDEX IX_CONTACTOS_CONTACTO ON CONTACTOS_CONFIANZA (CONTACTO_USUARIO_ID);
